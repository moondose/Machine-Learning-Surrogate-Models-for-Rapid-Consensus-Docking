#!/usr/bin/env python3
"""Predict molecular scores with the saved MBE or percentile-consensus ensemble.

Requires Python 3.9+, PyTorch >=2.3, NumPy, pandas, SciPy and scikit-learn.
Model architectures are imported from ../Training/model_utils.py.

Examples (run from this directory):
    python predict.py --descriptor-dir /path/to/descriptors \
        --model-dir ../Models/mbe --output /path/to/mbe_predictions.csv
    python predict.py --descriptor-dir /path/to/descriptors \
        --model-dir ../Models/percentile_consensus \
        --output /path/to/percentile_predictions.csv --device cpu

Inputs:
    Descriptor directory: X_features.npy, feature_names.csv and
    zinc_ids_aligned.csv, generated by generate_descriptors.py.
    Model directory: the complete ensemble, per-fold metadata/scalers and
    feature_names.csv. Both packaged models and the new trainers are supported.
    Metadata determines architecture; the exact feature-name order is checked.

Prediction:
    Replace nonfinite input features with zero, then apply each fold's saved
    x_mean/x_std. Run its model in evaluation mode with FP32 inference. Convert
    predictions back using that fold's y_std/y_mean and average across folds.
    No scaler is fitted to the new dataset. No docking target labels are needed.

Outputs:
    The requested CSV preserves descriptor row order and source ID columns,
    adding prediction mean, population standard deviation across folds,
    ensemble_folds and prediction_rank (lower mean is better; average tie rank).
    --sort sorts the CSV by predicted mean, retaining original row_index.
    <output>.run.json records model provenance, target definition, parameters,
    package versions, scaler/model hashes and timing.
    <output>.fold_runtime.csv records each fold's elapsed time.
    --save-fold-predictions writes <output>.fold_predictions.npy, whose rows
    follow descriptor order and columns follow fold number, even with --sort.

Use --device auto (default), cpu, cuda or cuda:0. --batch-size limits inference
memory. Descriptor arrays are memory-mapped and normalized one batch at a time;
--input-cache ram optionally keeps one cleaned float32 copy in RAM.
Choose a new output filename for each run. All fold predictions are in the
model target's original units. Percentile predictions are not clipped.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import time

import numpy as np
import pandas as pd
import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'Training'))
from model_utils import DockingMLP, SearchConsensusMLP


def scalar(metadata, key):
    return metadata[key].reshape(-1)[0].item()


def sha256(path):
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def ensemble_files(directory):
    """Use model layout and saved fold count; never silently drop missing folds."""
    config_path = directory / 'model_config.json'
    config = json.loads(config_path.read_text()) if config_path.is_file() else {}
    if (directory / 'fold_1/best_model.pt').is_file():
        kind = 'mbe'
        summary_path = directory / 'cv_summary.json'
    elif (directory / 'fold_1_best_model.pt').is_file():
        kind = 'percentile_consensus'
        summary_path = directory / 'summary.json'
    else:
        raise ValueError('No supported MBE or percentile ensemble found')
    summary = json.loads(summary_path.read_text()) if summary_path.is_file() else {}
    folds = int(config.get('folds', config.get('n_folds', summary.get('folds', summary.get('n_folds', 0)))))
    if folds < 2:
        raise ValueError('Saved config or summary must specify the ensemble fold count')
    result = []
    for fold in range(1, folds + 1):
        weights = directory / (f'fold_{fold}/best_model.pt' if kind == 'mbe' else f'fold_{fold}_best_model.pt')
        metadata = directory / (f'fold_{fold}/metadata.npz' if kind == 'mbe' else f'fold_{fold}_metadata.npz')
        if not weights.is_file() or not metadata.is_file():
            raise FileNotFoundError(f'Missing weights or metadata for fold {fold}')
        result.append((weights, metadata))
    return kind, config, result


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--descriptor-dir', type=Path, required=True)
    parser.add_argument('--model-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--x-file', default='X_features.npy')
    parser.add_argument('--batch-size', type=int, default=4096)
    parser.add_argument('--threads', type=int, default=4)
    parser.add_argument('--device', default='auto')
    parser.add_argument('--input-cache', choices=['none', 'ram'], default='none')
    parser.add_argument('--max-rows', type=int)
    parser.add_argument('--sort', action='store_true')
    parser.add_argument('--save-fold-predictions', action='store_true')
    args = parser.parse_args()
    if args.batch_size < 1 or args.threads < 1 or (args.max_rows is not None and args.max_rows < 1):
        parser.error('Batch size, threads and row limit must be positive')
    args.descriptor_dir = args.descriptor_dir.resolve()
    args.model_dir = args.model_dir.resolve()
    args.output = args.output.resolve()
    run_path = args.output.with_suffix('.run.json')
    runtime_path = args.output.with_suffix('.fold_runtime.csv')
    fold_path = args.output.with_suffix('.fold_predictions.npy')
    products = [args.output, run_path, runtime_path] + ([fold_path] if args.save_fold_predictions else [])
    if len(set(products)) != len(products):
        parser.error('Choose an output filename ending in .csv')
    for product in products:
        if product.exists():
            parser.error(f'Output already exists: {product}')
    torch.set_num_threads(args.threads)
    device = torch.device(('cuda' if torch.cuda.is_available() else 'cpu') if args.device == 'auto' else args.device)
    if device.type not in {'cpu','cuda'}:
        parser.error('Supported devices are cpu and cuda')
    if device.type == 'cuda' and not torch.cuda.is_available():
        parser.error('CUDA is unavailable; use --device cpu')
    started = time.monotonic()
    kind, config, paths = ensemble_files(args.model_dir)
    features = np.load(args.descriptor_dir / args.x_file, mmap_mode='r', allow_pickle=False)
    names = pd.read_csv(args.descriptor_dir / 'feature_names.csv', dtype='string').feature_name
    expected = pd.read_csv(args.model_dir / 'feature_names.csv', dtype='string').feature_name
    if names.isna().any() or names.duplicated().any() or names.tolist() != expected.tolist():
        raise ValueError('Descriptor feature names/order do not match the trained model')
    ids = pd.read_csv(args.descriptor_dir / 'zinc_ids_aligned.csv', dtype='string')
    if 'zinc_id' not in ids or ids.zinc_id.isna().any() or ids.zinc_id.str.strip().eq('').any() or ids.zinc_id.duplicated().any():
        raise ValueError('Input IDs must contain nonempty unique zinc_id values')
    if features.ndim != 2 or features.shape != (len(ids),len(names)) or not np.issubdtype(features.dtype,np.number):
        raise ValueError('Feature matrix shape/type does not match ID rows and feature names')
    if 'row_index' in ids and not np.array_equal(pd.to_numeric(ids.row_index, errors='coerce').to_numpy(), np.arange(len(ids))):
        raise ValueError('Input ID row_index does not match descriptor matrix order')
    count = min(len(ids),args.max_rows) if args.max_rows else len(ids)
    if not count:
        raise ValueError('No molecules to predict')
    ids = ids.iloc[:count].copy()
    ids['row_index'] = np.arange(count)
    features = features[:count]
    if args.input_cache == 'ram':
        clean = np.empty(features.shape,dtype=np.float32)
        for start in range(0,count,args.batch_size):
            clean[start:start+args.batch_size] = np.nan_to_num(
                np.asarray(features[start:start+args.batch_size],np.float32),nan=0.,posinf=0.,neginf=0.)
        features = clean
    args.output.parent.mkdir(parents=True,exist_ok=True)
    all_folds = (np.lib.format.open_memmap(fold_path,mode='w+',dtype=np.float32,shape=(count,len(paths)))
                 if args.save_fold_predictions else None)
    total = np.zeros(count,np.float64)
    squared = np.zeros(count,np.float64)
    records = []
    reference = None
    for fold,(weight_path,metadata_path) in enumerate(paths,1):
        fold_started = time.monotonic()
        with np.load(metadata_path,allow_pickle=False) as meta:
            dim = int(scalar(meta,'input_dim'))
            hidden = tuple(int(v) for v in meta['hidden_dims'])
            activation = str(scalar(meta,'activation'))
            dropout = float(scalar(meta,'dropout'))
            target = str(scalar(meta,'target_name' if kind=='mbe' else 'target'))
            mean = meta['x_mean'].astype(np.float32)
            std = meta['x_std'].astype(np.float32)
            ym,ys = float(scalar(meta,'y_mean')),float(scalar(meta,'y_std'))
            if 'fold' in meta and int(scalar(meta,'fold')) != fold:
                raise ValueError('Metadata fold number mismatch')
            if 'folds' in meta and int(scalar(meta,'folds')) != len(paths):
                raise ValueError('Metadata ensemble fold count mismatch')
        signature = (dim,hidden,activation,dropout,target)
        if reference is not None and signature != reference:
            raise ValueError('Fold architectures or target names differ')
        reference = signature
        if dim != len(names) or mean.shape != (dim,) or std.shape != (dim,):
            raise ValueError('Model/scaler feature dimensions differ from inputs')
        if not np.isfinite(mean).all() or not np.isfinite(std).all() or (std<=0).any() or not np.isfinite([ym,ys]).all() or ys<=0:
            raise ValueError('Invalid fold standardization parameters')
        model = (DockingMLP(dim,hidden,dropout,activation) if kind=='mbe'
                 else SearchConsensusMLP(dim,hidden,dropout,activation)).to(device)
        model.load_state_dict(torch.load(weight_path,map_location='cpu',weights_only=True),strict=True)
        model.eval()
        with torch.inference_mode():
            for start in range(0,count,args.batch_size):
                stop = min(start+args.batch_size,count)
                block = np.asarray(features[start:stop],np.float32)
                if args.input_cache == 'none':
                    block = np.nan_to_num(block,nan=0.,posinf=0.,neginf=0.)
                normalized = (block-mean)/std
                prediction = model(torch.from_numpy(normalized).to(device)).reshape(-1).cpu().numpy()*ys+ym
                if not np.isfinite(prediction).all():
                    raise ValueError(f'Nonfinite predictions in fold {fold}')
                total[start:stop] += prediction
                squared[start:stop] += prediction.astype(np.float64)**2
                if all_folds is not None:
                    all_folds[start:stop,fold-1] = prediction
        records.append(dict(fold=fold,weights=str(weight_path),metadata=str(metadata_path),
                            weights_sha256=sha256(weight_path),metadata_sha256=sha256(metadata_path),
                            elapsed_seconds=time.monotonic()-fold_started))
        del model
        print(f'Fold {fold}/{len(paths)}: predicted {count} molecules',flush=True)
    if all_folds is not None:
        all_folds.flush()
        del all_folds
    prediction = total/len(paths)
    prefix = 'predicted_mbe' if kind=='mbe' else 'predicted_percentile_consensus'
    ids[prefix+'_mean'] = prediction
    ids[prefix+'_std'] = np.sqrt(np.maximum(squared/len(paths)-prediction**2,0))
    ids['ensemble_folds'] = len(paths)
    ids['prediction_rank'] = pd.Series(prediction).rank(method='average',ascending=True).to_numpy()
    if args.sort:
        ids = ids.sort_values(prefix+'_mean',kind='stable')
    ids.to_csv(args.output,index=False)
    pd.DataFrame(records).to_csv(runtime_path,index=False)
    summary = dict(model_kind=kind,target=target,target_definition=config.get('target_definition'),
                   target_recipe=config.get('target_recipe'),
                   rows=count,features=len(names),folds=len(paths),device=str(device),precision='float32',
                   lower_is_better=True,fold_std='population standard deviation of fold predictions',
                   feature_schema_sha256=hashlib.sha256(('\n'.join(names)+'\n').encode()).hexdigest(),
                   input_order='descriptor order; row_index retained if sorted',
                   fold_prediction_order='descriptor rows by ascending fold number',
                   arguments={k:str(v) if isinstance(v,Path) else v for k,v in vars(args).items()},
                   versions=dict(torch=torch.__version__,numpy=np.__version__,pandas=pd.__version__),
                   elapsed_seconds=time.monotonic()-started,folds_metadata=records)
    run_path.write_text(json.dumps(summary,indent=2)+'\n')
    print(f'Saved {count} predictions: {args.output}',flush=True)


if __name__ == '__main__':
    main()
